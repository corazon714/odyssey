#!/usr/bin/env node
/**
 * PreToolUse / Write|Edit|MultiEdit|NotebookEdit — block writes to protected paths.
 *
 * PreToolUse is the correct event: it is the only one that can stop a write before it
 * lands. Exit 2 blocks the call and feeds stderr back as the reason.
 *
 * Deliberately does no I/O and spawns no subprocess — it is pure string work on the path
 * the tool was called with, so the cost is node startup (~60ms) and nothing else.
 */

import { readFileSync } from 'node:fs';

/** Each rule is [test, reason]. Paths are repo-relative, posix separators, lowercased. */
const PROTECTED = [
  [
    (p) => p === 'reports' || p.startsWith('reports/'),
    'reports/ holds generated simulation and balance output. CLAUDE.md §6: never commit ' +
      'reports/ output. It is regenerated by `pnpm sim` (planned), never hand-edited.',
  ],
  [
    (p) => p.startsWith('packages/content/images/generated/'),
    'Generated image assets are produced by the imagegen pipeline (planned), never written ' +
      'by hand. CLAUDE.md §6: never commit generated images.',
  ],
  [
    (p) => p.startsWith('apps/mobile/assets/generated/'),
    'Generated asset directory — written by the build-time image pipeline, not by hand.',
  ],
  [
    // .env.example is a committed template and stays writable.
    (p) => (p === '.env' || p.startsWith('.env.')) && !p.endsWith('.example'),
    'Environment files hold secrets and are gitignored. Never write credentials into the ' +
      'repo — put them in your shell environment or a local .env you create yourself.',
  ],
];

function repoRelative(filePath, cwd) {
  const norm = filePath.replace(/\\/g, '/');
  const root = (cwd ?? '').replace(/\\/g, '/').replace(/\/$/, '');
  const rel =
    root && norm.toLowerCase().startsWith(root.toLowerCase() + '/')
      ? norm.slice(root.length + 1)
      : norm;
  return rel.replace(/^\.\//, '').toLowerCase();
}

let raw = '';
try {
  raw = readFileSync(0, 'utf8');
} catch {
  process.exit(0); // No stdin: nothing to judge, do not obstruct.
}

let payload;
try {
  payload = JSON.parse(raw);
} catch {
  process.exit(0);
}

const input = payload.tool_input ?? {};
const target = input.file_path ?? input.notebook_path ?? input.path;
if (typeof target !== 'string' || target.length === 0) process.exit(0);

const rel = repoRelative(target, payload.cwd);

for (const [matches, reason] of PROTECTED) {
  if (matches(rel)) {
    process.stderr.write(
      `BLOCKED: write to protected path "${rel}".\n\n${reason}\n\n` +
        'If this is genuinely intended, tell the human what you are trying to write and why, ' +
        'and let them do it. Do not work around this hook.\n',
    );
    process.exit(2);
  }
}

process.exit(0);
